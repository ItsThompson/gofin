import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(scriptDir, "..");
const catalogPath = join(repoRoot, "shared/currency/catalog.json");
const frontendConstantsPath = join(repoRoot, "frontend/packages/core/src/constants.ts");
const goPackageDir = join(repoRoot, "services/shared/currency");
const goCatalogPath = join(goPackageDir, "catalog_gen.go");
const frontendCatalogPath = join(repoRoot, "frontend/packages/core/src/currency-catalog.json");

const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));

function validateCatalog(entries) {
  if (!Array.isArray(entries)) {
    throw new Error("currency catalog must be an array");
  }

  const seenCodes = new Set();
  for (const entry of entries) {
    if (typeof entry.code !== "string" || !/^[A-Z]{3}$/.test(entry.code)) {
      throw new Error(`invalid currency code: ${entry.code}`);
    }
    if (seenCodes.has(entry.code)) {
      throw new Error(`duplicate currency code: ${entry.code}`);
    }
    seenCodes.add(entry.code);

    if (typeof entry.symbol !== "string" || entry.symbol.length === 0) {
      throw new Error(`currency ${entry.code} is missing symbol`);
    }
    if (typeof entry.name !== "string" || entry.name.length === 0) {
      throw new Error(`currency ${entry.code} is missing name`);
    }
    if (!Number.isInteger(entry.minorUnitDigits) || entry.minorUnitDigits < 0) {
      throw new Error(`currency ${entry.code} has invalid minorUnitDigits`);
    }
  }
}

validateCatalog(catalog);

function tsObjectLiteral(entry) {
  return `{ code: ${JSON.stringify(entry.code)}, symbol: ${JSON.stringify(entry.symbol)}, name: ${JSON.stringify(entry.name)}, minorUnitDigits: ${entry.minorUnitDigits} }`;
}

function goDefinitionLiteral(entry) {
  return `{Code: ${JSON.stringify(entry.code)}, Symbol: ${JSON.stringify(entry.symbol)}, Name: ${JSON.stringify(entry.name)}, MinorUnitDigits: ${entry.minorUnitDigits}}`;
}

const tsCatalog = catalog.map((entry) => `  ${tsObjectLiteral(entry)},`).join("\n");
const goCatalog = catalog.map((entry) => `\t${goDefinitionLiteral(entry)},`).join("\n");
const goMapEntries = catalog.map((entry) => `\t${JSON.stringify(entry.code)}: ${goDefinitionLiteral(entry)},`).join("\n");

const constantsTs = `/** Valid expense type categories. */
export const EXPENSE_TYPES = ["essentials", "desires", "savings"] as const;

/** Derived type from EXPENSE_TYPES constant. */
export type ExpenseType = (typeof EXPENSE_TYPES)[number];

/** Default budget split percentages (must sum to 100). */
export const DEFAULT_BUDGET_SPLIT = {
  essentials: 50,
  desires: 30,
  savings: 20,
} as const;

// Code generated by scripts/generate-currency-catalog.mjs; DO NOT EDIT.
export const SUPPORTED_CURRENCIES = [
${tsCatalog}
] as const;

export type SupportedCurrency = (typeof SUPPORTED_CURRENCIES)[number];
export type SupportedCurrencyCode = SupportedCurrency["code"];
`;

const goCatalogGen = `// Code generated by scripts/generate-currency-catalog.mjs; DO NOT EDIT.

package currency

// Definition describes one supported currency.
type Definition struct {
\tCode            string
\tSymbol          string
\tName            string
\tMinorUnitDigits int
}

var supportedCurrencies = []Definition{
${goCatalog}
}

var catalog = map[string]Definition{
${goMapEntries}
}

func All() []Definition {
\tdefinitions := make([]Definition, len(supportedCurrencies))
\tcopy(definitions, supportedCurrencies)
\treturn definitions
}

func Get(code string) (Definition, bool) {
\tdefinition, ok := catalog[code]
\treturn definition, ok
}

func IsSupported(code string) bool {
\t_, ok := catalog[code]
\treturn ok
}
`;

writeFileSync(frontendConstantsPath, constantsTs);
writeFileSync(frontendCatalogPath, JSON.stringify(catalog, null, 2) + "\n");
mkdirSync(goPackageDir, { recursive: true });
writeFileSync(goCatalogPath, goCatalogGen);
execFileSync("gofmt", ["-w", goCatalogPath], { stdio: "inherit" });
